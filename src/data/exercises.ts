function buildSteps(def: Def): ExerciseInstructionStep[] {
  const other = def.s === 0 ? 1 : 0;
  return def.steps.map(([title, description, img], i) => {
    const idx = img === 'A' ? def.s : img === 'B' ? other : null;
    return {
      stepNumber: i + 1,
      title,
      description,
      imageUrl: idx === null ? null : `exercises/${def.id}/${idx}.jpg`,
      altText: idx === null ? `Kein Foto: ${def.name} – ${title}` : `${def.name} – ${title}`,
    };
  });
}

function build(def: Def): Exercise {
  return {
    id: def.id,
    name: def.name,
    description: def.desc,
    primaryMuscle: def.p,
    secondaryMuscles: def.sec,
    equipment: def.eq,
    difficulty: def.d,
    type: def.t,
    pattern: def.pat,
    instructions: def.ins,
    techniqueTips: def.tips,
    commonMistakes: def.err,
    safetyNotes: def.safe,
    recommended: { ...RR[def.t], ...def.rr },
    repUnit: def.unit ?? 'wdh',
    imageUrl: `exercises/${def.id}/${def.s === 0 ? 1 : 0}.jpg`,
    photoGuide: buildSteps(def),
    alternatives: [],
    isCustom: false,
    imageCredit: IMAGE_CREDIT,
  };
}

export const BUILTIN_EXERCISES: Exercise[] = DEFS.map(build);
